"""Generate agent/src/mpa/contract/models.py (Pydantic v2) from packages/contract/schema/*.json.

Every exported schema is self-contained (shared types live in its `$defs`), so the defs of all
files are merged into one bundle and fed to datamodel-code-generator once. Idempotent;
`--check` exits non-zero when the committed file is out of date.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_DIR = ROOT / "packages" / "contract" / "schema"
OUTPUT = ROOT / "agent" / "src" / "mpa" / "contract" / "models.py"
HEADER = (
    "# ruff: noqa\n"
    "# Generated by agent/scripts/gen_models.py from packages/contract/schema/*.json. "
    "DO NOT EDIT."
)


def build_bundle() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        schema = json.loads(path.read_text())
        for name, definition in schema.get("$defs", {}).items():
            if name in defs and defs[name] != definition:
                raise SystemExit(f"definition {name!r} differs between schema files")
            defs[name] = definition
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$defs": dict(sorted(defs.items())),
    }


def _union_roots(source: str) -> str:
    """Name the exported union schemas that the generator inlined into their users."""
    defs = build_bundle()["$defs"]
    extra = ""
    for path in sorted(SCHEMA_DIR.glob("*.json")):
        name = path.stem
        if f"class {name}(" in source:
            continue
        definition = defs[name]
        refs = [item["$ref"].rsplit("/", 1)[1] for item in definition.get("oneOf", [])]
        if not refs:
            raise SystemExit(f"cannot name root schema {name!r}")
        union = " | ".join(refs)
        extra += f"\n\nclass {name}(RootModel[{union}]):\n    root: {union}\n"
    return extra


def _ruff_format(source: str) -> str:
    ruff = Path(sys.executable).parent / "ruff"
    proc = subprocess.run(
        [str(ruff), "format", "--line-length", "100", "--stdin-filename", "models.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )
    return proc.stdout


def generate() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        bundle = Path(tmp) / "bundle.json"
        out = Path(tmp) / "models.py"
        bundle.write_text(json.dumps(build_bundle()))
        subprocess.run(
            [
                str(Path(sys.executable).parent / "datamodel-codegen"),
                "--input",
                str(bundle),
                "--input-file-type",
                "jsonschema",
                "--output",
                str(out),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.12",
                "--use-annotated",
                "--field-constraints",
                "--use-title-as-name",
                "--use-standard-collections",
                "--use-union-operator",
                "--use-double-quotes",
                "--disable-timestamp",
                "--enum-field-as-literal",
                "all",
                "--extra-fields",
                "forbid",
                "--custom-file-header",
                HEADER,
                "--formatters",
                "builtin",
                "--collapse-root-models",
                "--collapse-constrained-root-models-as-annotated",
            ],
            check=True,
        )
        source = out.read_text()
    stub = "class Model(RootModel[Any]):\n    root: Any\n\n\n"
    if stub not in source:
        raise SystemExit("expected the bundle root stub class in generated output")
    source = source.replace(stub, "") + _union_roots(source)
    return _ruff_format(source)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if models.py is stale")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print("models.py is out of date: run `uv run python scripts/gen_models.py`")
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
